import assert from 'node:assert/strict';
import { friendlyError, friendlyLogLine } from '../src/utils/friendlyError.js';
assert.match(friendlyError('upload rejected: could not extract archive: [WinError 206] The filename or extension is too long: "C:\\x"'), /path is too long for Windows/);
assert.match(friendlyError('Failed to fetch'), /Cannot reach the ChaosTutor backend/);
assert.match(friendlyError('No experiments generated for the selected project.'), /No tests are available/);
assert.equal(friendlyError('some brand new message'), 'some brand new message');
assert.match(friendlyError('Traceback (most recent call last):\n  File "x.py", line 3\nWeirdCustomError: bad'), /Something unexpected went wrong.*WeirdCustomError: bad/);
assert.match(friendlyError('file too large for Cloud IDE'), /editor/);
assert.match(friendlyError('file too large in repository: a.bin (9 bytes)'), /single file/);
assert.match(friendlyError('run /analyze before generating experiments'), /not been analysed/);
assert.match(friendlyError('no executable entrypoint detected'), /main file/);
assert.match(friendlyError('auth/invalid-credential'), /Email or password/);
assert.match(friendlyError("KeyError: 'id'"), /key 'id'/);
assert.match(friendlyError('Cannot read properties of undefined (reading x)'), /undefined or null/);
assert.match(friendlyError('experiment e1 is BLOCKED, not READY'), /not ready to run/);
assert.equal(friendlyLogLine('Injecting latency on /tasks'), 'Injecting latency on /tasks');
assert.equal(friendlyLogLine('Traceback (most recent call last):\nValueError: x'), 'Traceback (most recent call last):\nValueError: x');
assert.match(friendlyLogLine("ModuleNotFoundError: No module named 'flask'"), /Python package "flask"/);
console.log('friendlyError tests passed');
